import re
from typing import Dict, Any


class AmbiguityDetector:
    AMBIGUOUS_PATTERNS = [
        (r"یک مدرسه خاص", "نام یا کد مدرسه موردنظر را مشخص کنید."),
        (r"آن مدرسه", "نام مدرسه مورد نظر را ذکر کنید."),
        (r"این منطقه", "نام منطقه مورد نظر را ذکر کنید."),
        (r"آن منطقه", "نام منطقه مورد نظر را ذکر کنید."),
        (r"این کارمند", "نام یا کد ملی کارمند مورد نظر را ذکر کنید."),
        (r"آن کارمند", "نام یا کد ملی کارمند مورد نظر را ذکر کنید."),
        (r"بازه موردنظر", "بازه زمانی مشخص نشده. تاریخ شروع و پایان را ذکر کنید."),
        (r"بازه مورد نظر", "بازه زمانی مشخص نشده. تاریخ شروع و پایان را ذکر کنید."),
        (r"این تاریخ", "تاریخ مشخص نشده. تاریخ مورد نظر را ذکر کنید."),
        (r"آن تاریخ", "تاریخ مشخص نشده. تاریخ مورد نظر را ذکر کنید."),
        (r"این ماه", "ماه مشخص نشده. ماه مورد نظر را ذکر کنید."),
        (r"آن ماه", "ماه مشخص نشده. ماه مورد نظر را ذکر کنید."),
        (r"این سال", "سال مشخص نشده. سال مورد نظر را ذکر کنید."),
        (r"آن سال", "سال مشخص نشده. سال مورد نظر را ذکر کنید."),
        (r"همان سال", "سال مشخص نشده. سال مورد نظر را ذکر کنید."),
        (r"همان منطقه", "نام منطقه مورد نظر را ذکر کنید."),
        (r"همان مدرسه", "نام مدرسه مورد نظر را ذکر کنید."),
        (r"مذکور", "PointerException مشخص نشده. مورد مورد نظر را ذکر کنید."),
        (r"موردنظر", "PointerException مشخص نشده. مورد مورد نظر را ذکر کنید."),
    ]
    
    REFERENCE_DEMONSTRATIVES = ["این", "آن", "همان", "مذکور", "موردنظر"]
    
    def detect(self, question: str) -> Dict[str, Any]:
        for pattern, clarification in self.AMBIGUOUS_PATTERNS:
            if re.search(pattern, question):
                return {
                    "needs_clarification": True,
                    "clarification_question": clarification
                }
        
        return {
            "needs_clarification": False,
            "clarification_question": None
        }


ambiguity_detector = AmbiguityDetector()
